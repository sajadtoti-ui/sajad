String _n(String x) => x
    .toLowerCase()
    .replaceAll(RegExp('[أإآ]'), 'ا')
    .replaceAll('ة', 'ه')
    .replaceAll('ى', 'ي');

/// يرجع أقرب جواب، أو null إذا ما فهم السؤال
Faq? findFaq(String text, String role) {
  final t = _n(text);
  Faq? best;
  var score = 0;
  for (final f in kFaq) {
    if (f.role != 'all' && f.role != role) continue;
    var s = 0;
    for (final k in f.keys) {
      if (t.contains(_n(k))) s += k.length;
    }
    if (s > score) {
      score = s;
      best = f;
    }
  }
  return best;
}
